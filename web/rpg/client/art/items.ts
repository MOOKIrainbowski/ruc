/**
 * 템플릿 · 희귀도 → 64×64 캔버스 (2026-11-14 피드백: 예전 스타일 그대로, 픽셀 수만 늘림).
 * 예전과 같은 12×12 격자 그림 → Scale2x 두 번(16 → 32 → 64, 계단 모서리가 매끈한 곡선으로) → 명암 마감(refine).
 * UI 는 32px 칸에 그대로 넣음 — 화면 배율 · 고해상도 화면에서 4배 픽셀이 보임. 바닥 아이템은 해상도 2 텍스처(game.ts).
 */
export function itemIcon(tpl: string, rarity: Rarity): HTMLCanvasElement {
  const o = overrides.items.get(tpl); // 진짜 그림 (P17)
  if (o) return o;
  const t = ITEMS[tpl];
  const gear = !!t && isGear(t);
  const own = TPL_PAL[tpl];
  const key = `${own || t?.kind === "armor" ? tpl : t?.icon}:${gear ? rarity : ""}`;
  let c = cache.get(key);
  if (!c) {
    const p = new Px(16, 16);
    const [main, light, shade] = own ?? (t?.kind === "armor" ? armorPalette(t, rarity) : gear ? METAL[rarity] : OWN[t?.icon ?? ""] ?? METAL.common);
    const pal: Record<string, string> = { ...FIXED, ...EXTRA, "+": main, "*": light, "-": shade };
    (ART[t?.icon ?? ""] ?? ART.stone).forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") p.set(2 + x, 2 + y, pal[ch] ?? main); }));
    if (gear && rarity === "legendary") { p.set(13, 1, "#ffffff"); p.set(12, 2, "#fff4b0"); p.set(14, 2, "#fff4b0"); p.set(13, 3, "#fff4b0"); }
    c = refine(p, 2).toCanvas(); // 16×16 → 64×64
    cache.set(key, c);
  }
  return c;
}
