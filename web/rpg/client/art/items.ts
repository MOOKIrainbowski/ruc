const cache = new Map<string, HTMLCanvasElement>();

/** 템플릿 · 희귀도 → 16×16 캔버스 (희귀도는 장비만 색이 바뀜) */
export function itemIcon(tpl: string, rarity: Rarity): HTMLCanvasElement {
  const t = ITEMS[tpl];
  const gear = !!t && isGear(t);
  const key = `${t?.icon}:${gear ? rarity : ""}`;
  let c = cache.get(key);
  if (!c) {
    const p = new Px(16, 16);
    const [main, light, shade] = gear ? METAL[rarity] : OWN[t?.icon ?? ""] ?? METAL.common;
    const pal: Record<string, string> = { ...FIXED, "+": main, "*": light, "-": shade };
    (ART[t?.icon ?? ""] ?? ART.stone).forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") p.set(2 + x, 2 + y, pal[ch]); }));
    if (gear && rarity === "legendary") { p.set(13, 1, "#ffffff"); p.set(12, 2, "#fff4b0"); p.set(14, 2, "#fff4b0"); p.set(13, 3, "#fff4b0"); }
    c = refine32(p).toCanvas(); // 32×32 세밀한 아이콘
    cache.set(key, c);
  }
  return c;
}
