/** 스킬 아이콘 — bg = 속성 · 계열 배경색. 12×12 그림이 없으면 7×7 글리프를 두 배로 (직업 스킬, §10-5) */
export function skillIcon(id: string, bg = "#5a3b7a"): HTMLCanvasElement {
  return memo(`sk:${id}:${bg}`, () => {
    const p = new Px(16, 16);
    p.rect(0, 0, 16, 16, OUTLINE);
    p.rect(1, 1, 14, 14, darken(bg, 0.35));
    p.rect(1, 1, 14, 1, lighten(bg, 0.2));
    p.rect(1, 1, 1, 14, lighten(bg, 0.2));
    const s = S[id];
    if (s) s.rows.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") p.set(2 + x, 2 + y, s.pal[ch]); }));
    else glyph(p, G[id] ? id : "sparkle", 1, 1, lighten(bg, 0.7));
    return p;
  });
}
