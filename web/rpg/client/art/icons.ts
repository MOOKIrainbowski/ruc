function lighten(hex: string, k: number) {
  const n = parseInt(hex.slice(1, 7), 16);
  const c = [n >> 16, (n >> 8) & 255, n & 255].map((v) => Math.round(v + (255 - v) * k));
  return `#${c.map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}
function darken(hex: string, k: number) {
  const n = parseInt(hex.slice(1, 7), 16);
  const c = [n >> 16, (n >> 8) & 255, n & 255].map((v) => Math.round(v * (1 - k)));
  return `#${c.map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}

/** 글리프를 (ox, oy) 에 scale 배로 */
function glyph(p: Px, name: string, ox: number, oy: number, color: string, scale = 2) {
  const g = G[name] ?? G.sparkle;
  const light = lighten(color, 0.55);
  g.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch !== ".") p.rect(ox + x * scale, oy + y * scale, scale, scale, ch === "+" ? light : color);
  }));
}

const cache = new Map<string, HTMLCanvasElement>();
const urls = new WeakMap<HTMLCanvasElement, string>();
const memo = (key: string, make: () => Px) => {
  let c = cache.get(key);
  if (!c) { c = make().toCanvas(); cache.set(key, c); }
  return c;
};
/** HUD(img) 용 data URL */
export const iconUrl = (c: HTMLCanvasElement) => {
  let u = urls.get(c);
  if (!u) { u = c.toDataURL(); urls.set(c, u); }
  return u;
};

/** 버프 · 디버프 아이콘 — 버프는 초록 테두리, 디버프는 빨간 테두리 (§23-2) */
export function effectIcon(id: string): HTMLCanvasElement {
  return memo(`fx:${id}`, () => {
    const d = effectDef(id);
    const p = new Px(16, 16);
    const col = d?.color ?? "#ffffff";
    p.rect(0, 0, 16, 16, d?.buff ? "#4CC764" : "#E5484D");
    p.rect(1, 1, 14, 14, darken(col === "#ffffff" || col === "#f2f2f2" ? "#9AA3AD" : col, 0.65));
    glyph(p, d?.icon ?? "sparkle", 1, 1, lighten(col, 0.1));
    return p;
  });
}

/** 스탯창 아이콘 (테두리 없음) */
export function statIcon(glyphName: string, color: string): HTMLCanvasElement {
  return memo(`st:${glyphName}:${color}`, () => {
    const p = new Px(16, 16);
    glyph(p, glyphName, 1, 1, color);
    p.outline();
    return p;
  });
}

